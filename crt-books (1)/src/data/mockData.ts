export function interestNameToSlug(name: string): string {
  const found = INTEREST_CATALOG.find(
    (i) => i.name.toLowerCase() === name.toLowerCase() || i.slug === name
  );
  return found ? found.slug : 'discipline_focus';
}

export function interestSlugToName(slugOrName: string): string {
  const found = INTEREST_CATALOG.find(
    (i) => i.slug === slugOrName || i.name.toLowerCase() === slugOrName.toLowerCase()
  );
  return found ? found.name : slugOrName;
}

export function dailyTimeToMinutes(dailyTime: string): number {
  if (dailyTime.startsWith('5')) return 5;
  if (dailyTime.startsWith('10')) return 10;
  if (dailyTime.startsWith('30')) return 30;
  return 20;
}

export function minutesToDailyTime(minutes: number): string {
  if (minutes === 5) return '5 minutos';
  if (minutes === 10) return '10 minutos';
  if (minutes >= 30) return '30+ minutos';
  return '20 minutos';
}

